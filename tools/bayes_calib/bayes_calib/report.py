def plot_corner(post: Posterior, path: Path) -> Path:
    """Pairwise posterior. Diagonal: posterior histogram vs PRIOR curve.

    Where the histogram is much narrower than the dashed prior, the data taught
    us something. Where they overlap, the data were silent. Off-diagonal
    banana/ridge shapes are parameter trade-offs (correlation).
    """
    x = post.theta
    d = x.shape[1]
    fig, ax = plt.subplots(d, d, figsize=(2.2 * d, 2.2 * d))
    for i in range(d):
        for j in range(d):
            a = ax[i, j]
            if j > i:
                a.axis("off")
                continue
            if i == j:
                a.hist(x[:, i], bins=40, density=True, color="#3b6ea5", alpha=0.85)
                g = np.linspace(x[:, i].min(), x[:, i].max(), 200)
                a.plot(g, norm.pdf(g, post.prior.mean[i], post.prior.sd[i]), "k--", lw=1)
                a.set_yticks([])
            else:
                a.hist2d(x[:, j], x[:, i], bins=40, cmap="Blues")
            if i == d - 1:
                a.set_xlabel(PARAM_NAMES[j], fontsize=8)
            if j == 0 and i > 0:
                a.set_ylabel(PARAM_NAMES[i], fontsize=8)
            a.tick_params(labelsize=6)
    fig.suptitle("Posterior (blue) vs prior (dashed)", y=0.995)
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)
    return path


def plot_trace(post: Posterior, path: Path, n_show: int = 8) -> Path:
    """Walker traces. Healthy = fuzzy caterpillar after the burn-in line."""
    s = post.chain.samples
    fig, ax = plt.subplots(s.shape[2], 1, figsize=(8, 1.7 * s.shape[2]), sharex=True)
    for j in range(s.shape[2]):
        ax[j].plot(s[:, :n_show, j], lw=0.4, alpha=0.7)
        ax[j].axvline(post.burn, color="r", lw=1)
        ax[j].set_ylabel(PARAM_NAMES[j], fontsize=8)
    ax[-1].set_xlabel("step  (red line = end of burn-in, earlier samples discarded)")
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)
    return path


def plot_prediction(post: Posterior, data: Dataset, path: Path, n_use: int = 400) -> Path:
    """Life vs ΔW with 90 % credible band, one panel per pad diameter, data overlaid."""
    rng = np.random.default_rng(0)
    th = post.theta[rng.choice(len(post.theta), min(n_use, len(post.theta)), replace=False)]
    diameters = sorted(set(np.round(data.d_mm, 6)))
    fig, axes = plt.subplots(1, len(diameters), figsize=(5 * len(diameters), 4), squeeze=False)
    grid = np.geomspace(data.dw.min() * 0.7, data.dw.max() * 1.4, 80)
    for ax, dia in zip(axes[0], diameters):
        eta = np.exp(ln_characteristic_life(th, grid, np.full_like(grid, dia)))
        lo, med, hi = np.percentile(eta, [5, 50, 95], axis=0)
        ax.fill_between(grid, lo, hi, color="#3b6ea5", alpha=0.25, label="90 % credible (η)")
        ax.plot(grid, med, color="#3b6ea5", label="median η")
        m = np.isclose(data.d_mm, dia)
        ax.scatter(data.dw[m & data.failed], data.cycles[m & data.failed],
                   s=14, c="k", label="failed", zorder=3)
        ax.scatter(data.dw[m & ~data.failed], data.cycles[m & ~data.failed],
                   s=22, facecolors="none", edgecolors="r", marker="v",
                   label="suspended", zorder=3)
        ax.set_xscale("log"); ax.set_yscale("log")
        ax.set_xlabel("ΔW  [MPa]"); ax.set_ylabel("cycles")
        ax.set_title(f"pad Ø {dia:g} mm")
        ax.grid(True, which="both", alpha=0.25)
    axes[0, 0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)
    return path
