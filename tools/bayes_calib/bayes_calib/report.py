"""Turn a Posterior into files a human (and the solver) can use."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # no display needed
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import norm

from .calibrate import Posterior
from .model import NATURAL_NAMES, PARAM_NAMES, Dataset, ln_characteristic_life, to_natural

PCT = (2.5, 50.0, 97.5)


def summarize(post: Posterior) -> dict:
    nat = post.natural
    prior_sd = post.prior.sd
    out = {}
    for j, name in enumerate(NATURAL_NAMES):
        lo, med, hi = np.percentile(nat[:, j], PCT)
        # Shrinkage: how much the data narrowed this parameter, measured on the
        # sampled (log) scale where the prior is Gaussian. ~0 % => data said
        # nothing and the answer is just the prior; ~90 % => well determined.
        shrink = 1.0 - post.theta[:, j].std() / prior_sd[j]
        out[name] = {
            "mean": float(nat[:, j].mean()), "sd": float(nat[:, j].std()),
            "p2.5": float(lo), "median": float(med), "p97.5": float(hi),
            "shrinkage_vs_prior": float(shrink),
            "autocorr_time": float(post.tau[j]), "ess": float(post.ess[j]),
        }
    return out


def text_summary(post: Posterior, data: Dataset) -> str:
    s = summarize(post)
    n_fail = int(data.failed.sum())
    lines = [
        f"Specimens: {len(data)}  (failed {n_fail}, censored {len(data) - n_fail})",
        f"Sampler  : acceptance {post.chain.acceptance:.2f}, "
        f"{len(post.theta)} posterior draws kept",
        "",
        f"{'param':<6}{'median':>11}{'2.5%':>11}{'97.5%':>11}{'shrink':>9}{'ESS':>8}",
    ]
    for name in NATURAL_NAMES:
        r = s[name]
        lines.append(f"{name:<6}{r['median']:>11.4g}{r['p2.5']:>11.4g}{r['p97.5']:>11.4g}"
                     f"{r['shrinkage_vs_prior'] * 100:>8.0f}%{r['ess']:>8.0f}")
    warn = []
    if post.acceptance_bad():
        warn.append("acceptance fraction outside 0.1-0.7: results may be unreliable")
    if np.any(post.ess < 200):
        warn.append("ESS < 200 for some parameter: increase --steps")
    if np.any(post.chain.samples.shape[0] - post.burn < 50 * post.tau):
        warn.append("chain shorter than 50 x autocorrelation time: not converged, increase --steps")
    weak = [n for n in ("K1", "K2", "K3", "K4") if s[n]["shrinkage_vs_prior"] < 0.25]
    if weak:
        warn.append(f"data barely constrain {', '.join(weak)} individually (posterior ~ prior). "
                    "Trust the predicted life curve, not these constants. See README 'Identifiability'.")
    if warn:
        lines += ["", "WARNINGS:"] + [f"  ! {w}" for w in warn]
    return "\n".join(lines)


def pcsim_override(post: Posterior, material_id: int = 4) -> str:
    """Snippet for a .pcsim deck (parsed by rpim_solver pcsim_reader.rs).

    Uses the maximum-posterior DRAW rather than the marginal medians, because
    K1/K3 and K2/K4 are correlated: medians taken one at a time can combine
    into a parameter set the data never supported. One coherent draw can't.
    """
    k1, k2, k3, k4, _ = to_natural(post.theta_map[None, :])[0]
    return (
        f"# Generated by bayes_calib. Posterior MAP draw (coherent parameter set).\n"
        f"*MATERIAL_OVERRIDE, ID={material_id}\n"
        f"DARVEAUX_K1={k1:.6g}\nDARVEAUX_K2={k2:.6g}\n"
        f"DARVEAUX_K3={k3:.6g}\nDARVEAUX_K4={k4:.6g}\n"
    )


def write_all(post: Posterior, data: Dataset, out_dir: str | Path, material_id: int = 4) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    files = []

    p = out / "posterior.json"
    p.write_text(json.dumps({"summary": summarize(post),
                             "map_natural": dict(zip(NATURAL_NAMES,
                                                     map(float, to_natural(post.theta_map[None, :])[0])))},
                            indent=2), encoding="utf-8")
    files.append(p)

    p = out / "summary.txt"
    p.write_text(text_summary(post, data) + "\n", encoding="utf-8")
    files.append(p)

    p = out / "pcsim_override.txt"
    p.write_text(pcsim_override(post, material_id), encoding="utf-8")
    files.append(p)

    p = out / "posterior_samples.npz"
    np.savez_compressed(p, theta=post.theta, names=np.array(PARAM_NAMES))
    files.append(p)

    files += [plot_corner(post, out / "corner.png"),
              plot_trace(post, out / "trace.png"),
              plot_prediction(post, data, out / "prediction.png")]
    return files


